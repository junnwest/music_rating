export function getAlbumById(id: string): Album | undefined {
  return albums.find(a => a.id === id);
}

export function getArtistById(id: string): Artist | undefined {
  return artists.find(a => a.id === id);
}

export function getAlbumsByArtist(artistId: string): Album[] {
  return albums.filter(a => a.artistId === artistId).sort((a, b) => b.year - a.year);
}

export function getAlbumsByGenre(genre: string): Album[] {
  return albums.filter(a => a.genres.includes(genre)).sort((a, b) => b.year - a.year);
}

