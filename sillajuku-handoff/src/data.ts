export interface Album {
  id: string;
  title: string;
  artist: string;
  artistId: string;
  year: number;
  type: 'Album' | 'EP' | 'Single' | 'Compilation';
  genres: string[];
  rating?: number;
  avgRating: number;
  ratingCount: number;
  reviewCount: number;
  coverGradient: string;
  tracks?: Track[];
  review?: string;
}

export interface Track {
  number: number;
  title: string;
  duration: string;
}

export interface Artist {
  id: string;
  name: string;
  genres: string[];
  followers: string;
  releases: number;
  avatarGradient: string;
}

export interface Review {
  id: string;
  user: string;
  userInitial: string;
  albumId: string;
  rating: number;
  text: string;
  timeAgo: string;
}

export interface ActivityItem {
  id: string;
  user: string;
  userInitial: string;
  type: 'rating' | 'review';
  albumId: string;
  rating: number;
  text?: string;
  timeAgo: string;
}

export interface Ranking {
  id: string;
  title: string;
  country: string;
  genre: string;
  votes: number;
  coverGradients: string[];
  items: RankingItem[];
}

export interface RankingItem {
  rank: number;
  albumId: string;
  votes: number;
}

export interface CuratedList {
  id: string;
  title: string;
  description: string;
  author: string;
  authorInitial: string;
  albumCount: number;
  createdAt: string;
  albumIds: string[];
}

